'use client';

import { useCallback, useEffect, useState } from 'react';
import Link from 'next/link';
import { Bell, CheckCheck, Loader2 } from 'lucide-react';
import { toast } from 'sonner';
import { EmptyState } from '@/components/common/EmptyState';
import { ErrorState } from '@/components/common/ErrorState';
import { PageHeader } from '@/components/common/PageHeader';
import { Pagination } from '@/components/common/Pagination';
import { Skeleton } from '@/components/common/Skeleton';
import { StatusPill } from '@/components/common/StatusPill';
import { Button } from '@/components/ui/button';
import { Card } from '@/components/ui/card';
import { notificationsApi } from '@/lib/api/endpoints';
import { getApiErrorMessage } from '@/lib/api/errors';
import type { NotificationItem } from '@/lib/api/types';
import { formatDateTime, prettyLabel } from '@/lib/utils';

const LIMIT = 20;
const FETCH_LIMIT = 100;

export default function NotificationsPage() {
  const [allItems, setAllItems] = useState<NotificationItem[]>([]);
  const [items, setItems] = useState<NotificationItem[]>([]);
  const [total, setTotal] = useState(0);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState('');
  const [filter, setFilter] = useState<'all' | 'unread'>('all');
  const [page, setPage] = useState(0);
  const [busyIds, setBusyIds] = useState<number[]>([]);
  const [markingAll, setMarkingAll] = useState(false);

  const load = useCallback(async () => {
    setLoading(true);
    setError('');
    try {
      const result = await notificationsApi.list({ limit: FETCH_LIMIT });
      setAllItems(result.items);
    } catch (cause) {
      setError(getApiErrorMessage(cause, 'Unable to load notifications.'));
    } finally {
      setLoading(false);
    }
  }, []);

  useEffect(() => {
    void load();
  }, [load]);

  async function markRead(item: NotificationItem) {
    if (item.read_at || busyIds.includes(item.id)) return;
    setBusyIds((current) => [...current, item.id]);
    try {
      await notificationsApi.markRead(item.id);
      setItems((current) => current.map((entry) => (entry.id === item.id ? { ...entry, read_at: new Date().toISOString() } : entry)));
      toast.success('Notification marked as read.');
      if (filter === 'unread') await load();
    } catch (cause) {
      toast.error(getApiErrorMessage(cause, 'Unable to mark this notification as read.'));
    } finally {
      setBusyIds((current) => current.filter((id) => id !== item.id));
    }
  }

  async function markAllRead() {
    const unread = items.filter((item) => !item.read_at);
    if (unread.length === 0) return;
    setMarkingAll(true);
    try {
      const results = await Promise.allSettled(unread.map((item) => notificationsApi.markRead(item.id)));
      const failed = results.filter((result) => result.status === 'rejected').length;
      if (failed === 0) toast.success(`${unread.length} notification${unread.length === 1 ? '' : 's'} marked as read.`);
      else toast.error(`${failed} notification${failed === 1 ? '' : 's'} could not be marked as read.`);
      await load();
    } finally {
      setMarkingAll(false);
    }
  }

  const unreadCount = allItems.filter((item) => !item.read_at).length;

  useEffect(() => {
    const filtered = filter === 'unread' ? allItems.filter((item) => !item.read_at) : allItems;
    setTotal(filtered.length);
    setItems(filtered.slice(page * LIMIT, page * LIMIT + LIMIT));
    if (page > 0 && page * LIMIT >= filtered.length) setPage(0);
  }, [allItems, filter, page]);

  return (
    <div className="space-y-7">
      <PageHeader
        eyebrow="Workspace tools"
        title="Notifications"
        description="Real updates generated by ticket activity in your workspace."
        icon={<Bell className="h-6 w-6" aria-hidden="true" />}
        actions={
          <>
            <Button
              variant="outline"
              onClick={() => { setFilter(filter === 'all' ? 'unread' : 'all'); setPage(0); }}
              aria-pressed={filter === 'unread'}
            >
              {filter === 'all' ? 'Show unread only' : 'Show all'}
            </Button>
            <Button variant="teal" onClick={() => void markAllRead()} disabled={markingAll || unreadCount === 0}>
              {markingAll ? <Loader2 className="h-4 w-4 animate-spin" aria-hidden="true" /> : <CheckCheck className="h-4 w-4" aria-hidden="true" />}
              Mark page as read
            </Button>
          </>
        }
      />

      {error ? <ErrorState title="Notifications unavailable" message={error} onRetry={() => void load()} /> : null}
      {loading ? (
        <div className="space-y-3">
          <Skeleton className="h-24" />
          <Skeleton className="h-24" />
          <Skeleton className="h-24" />
        </div>
      ) : null}

      {!loading && !error && items.length === 0 ? (
        <EmptyState
          title={filter === 'unread' ? 'No unread notifications' : 'No notifications yet'}
          message={filter === 'unread' ? 'You have read every notification in this view.' : 'Ticket updates will appear here when they are generated.'}
          icon={<Bell className="h-5 w-5" aria-hidden="true" />}
        />
      ) : null}

      {!loading && !error && items.length > 0 ? (
        <ul className="space-y-3">
          {items.map((item) => (
            <li key={item.id}>
              <Card className={`p-5 sm:p-6 ${item.read_at ? '' : 'border-teal-200 bg-teal-50/30'}`}>
                <div className="flex flex-wrap items-start justify-between gap-3">
                  <div className="min-w-0">
                    <div className="flex flex-wrap items-center gap-2">
                      <p className="text-sm font-semibold text-navy-900">{item.subject ?? prettyLabel(item.event_type)}</p>
                      <StatusPill status={item.read_at ? 'closed' : 'new'} label={item.read_at ? 'Read' : 'Unread'} />
                      <StatusPill status={item.status === 'sent' || item.status === 'delivered' ? 'healthy' : 'planned'} label={prettyLabel(item.status)} />
                    </div>
                    <p className="mt-2 whitespace-pre-wrap text-sm leading-relaxed text-slate-700">{item.body}</p>
                    <p className="mt-2 text-xs text-slate-500">
                      {formatDateTime(item.created_at)} · {prettyLabel(item.channel)}
                    </p>
                    {item.last_error ? <p className="mt-1 text-xs text-rose-600">{item.last_error}</p> : null}
                  </div>
                  <div className="flex flex-wrap gap-2">
                    {item.ticket_id ? (
                      <Button asChild variant="outline" size="sm">
                        <Link href={`/tickets/${item.ticket_id}`}>View ticket</Link>
                      </Button>
                    ) : null}
                    {!item.read_at ? (
                      <Button size="sm" variant="ghost" onClick={() => void markRead(item)} disabled={busyIds.includes(item.id)}>
                        {busyIds.includes(item.id) ? <Loader2 className="h-3.5 w-3.5 animate-spin" aria-hidden="true" /> : <CheckCheck className="h-3.5 w-3.5" aria-hidden="true" />}
                        Mark as read
                      </Button>
                    ) : null}
                  </div>
                </div>
              </Card>
            </li>
          ))}
        </ul>
      ) : null}

      <Pagination page={page} limit={LIMIT} total={total} onPageChange={setPage} />
    </div>
  );
}
